"""Generate RESULTS.md from computed aggregates.

Markdown tables use single hyphen delimiter rows so the file contains no double dashes.
"""
from __future__ import annotations

import math

import pandas as pd


def md_table(df: pd.DataFrame) -> str:
    cols = list(df.columns)
    lines = ["| " + " | ".join(str(c) for c in cols) + " |", "|" + "|".join("-" for _ in cols) + "|"]
    for _, r in df.iterrows():
        cells = []
        for c in cols:
            v = r[c]
            if isinstance(v, float):
                cells.append("" if math.isnan(v) else f"{v:g}")
            else:
                cells.append(str(v))
        lines.append("| " + " | ".join(cells) + " |")
    return "\n".join(lines)


def ci(lo, hi, nd=2):
    return f"{lo:.{nd}f} to {hi:.{nd}f}"


def pfmt(p):
    return "<0.001" if p < 0.001 else f"{p:.3f}"


def model_table(models: pd.DataFrame, outcome: str, nd: int) -> pd.DataFrame:
    sub = models[models.outcome == outcome]
    labels = list(dict.fromkeys(sub["label"]))
    rows = []
    for lab in labels:
        row = {"Predictor": lab}
        for meth, short in [("complete case", "Complete case"), (None, "Multiple imputation")]:
            s = sub[(sub.label == lab) & ((sub.method == meth) if meth else sub.method.str.startswith("multiple"))]
            if len(s):
                s = s.iloc[0]
                row[f"{short} (95% CI)"] = f"{s.estimate:.{nd}f} ({ci(s.ci_low, s.ci_high, nd)})"
                row[f"{short} p"] = pfmt(s.p)
        rows.append(row)
    return pd.DataFrame(rows)


